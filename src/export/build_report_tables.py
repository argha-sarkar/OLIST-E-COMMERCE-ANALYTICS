"""Turn the result tables into reports/results_pack.md.

Why generate the report instead of writing it by hand? Because a hand-written
report drifts from the code the moment either changes. Every number in this file
is read from reports/tables/*.csv, which were written by the analysis modules.
"""
from __future__ import annotations

import json

import pandas as pd

from src import config
from src.utils import LOG, md_table


def _read(name: str) -> pd.DataFrame:
    path = config.TABLES_DIR / f"{name}.csv"
    if not path.exists():
        LOG.warning("missing table %s", name)
        return pd.DataFrame()
    return pd.read_csv(path)


def build() -> str:
    config.ensure_dirs()
    manifest = {}
    mpath = config.REPORTS_DIR / "run_manifest.json"
    if mpath.exists():
        manifest = json.loads(mpath.read_text(encoding="utf-8"))

    head = _read("14_delivery_headline")
    seg = _read("06_rfm_segments")
    rep = _read("07_rfm_repeat_rate")
    monthly = _read("01_revenue_monthly")
    conc = _read("27_seller_concentration")

    lines: list[str] = []
    a = lines.append

    a("# Results Pack")
    a("")
    a("_Auto-generated by `src/export/build_report_tables.py` from `reports/tables/*.csv`._")
    a("_Do not edit by hand -- re-run `make analyze && make report`._")
    a("")
    if manifest:
        a(f"- generated: **{manifest.get('generated_at')}**  ·  source: `{manifest.get('data_source')}`")
        rows = manifest.get("rows", {})
        a(f"- orders: **{rows.get('orders', 0):,}**  ·  revenue orders: **{rows.get('revenue_orders', 0):,}**"
          f"  ·  delivered: **{rows.get('delivered_orders', 0):,}**"
          f"  ·  unique customers: **{rows.get('unique_customers', 0):,}**")
        a(f"- window starts **{manifest.get('analysis_start_month')}**  ·  "
          f"CLV margin assumption **{manifest.get('gross_margin_assumption')}**")
        a("")

    # ------------------------------------------------------------ headline
    a("## Headline numbers (copy these into README section 6 and docs/06)")
    a("")
    rows = []
    if not rep.empty:
        correct = rep.iloc[0]
        rows.append(("Repeat-purchase rate (correct basis)", f"{correct['repeat_rate_pct']:.2f}%"))
    if not head.empty:
        h = head.iloc[0]
        rows.append(("Late-delivery rate (delivered orders)", f"{h['late_rate_pct']:.2f}%"))
        rows.append(("Median delivery days", f"{h['median_delivery_days']:.0f}"))
        rows.append(("Avg review score, late orders", "see section 5"))
    if not conc.empty:
        c = conc.iloc[0]
        rows.append(("Share of GMV from top 20% of sellers", f"{c['top_20pct_share']:.1f}%"))
        rows.append(("Sellers needed to reach 80% of GMV", f"{c['sellers_to_reach_80pct']:,}"))
    if not seg.empty:
        champ = seg.sort_values("pct_of_gmv", ascending=False).iloc[0]
        rows.append(("Largest segment by revenue", f"{champ['segment']} ({champ['pct_of_gmv']:.1f}% of GMV)"))
    a(md_table(pd.DataFrame(rows, columns=["metric", "value"])))
    a("")

    # ------------------------------------------------------------ sections
    sections = [
        ("1. Revenue and growth (BQ1)", ["01_revenue_monthly", "02_revenue_by_state",
                                        "03_revenue_payment_mix", "04_revenue_price_bands",
                                        "05_revenue_new_vs_returning"]),
        ("2. Customer base and RFM (BQ2)", ["06_rfm_segments", "07_rfm_repeat_rate",
                                            "08_rfm_clv_proxy"]),
        ("3. Cohort retention (BQ2)", ["11_cohort_matrix", "12_cohort_curve", "13_repeat_timing"]),
        ("4. Delivery performance (BQ3)", ["14_delivery_headline", "15_delivery_percentiles",
                                           "16_delivery_by_state", "17_delivery_by_distance",
                                           "18_delivery_decomposition", "19_delivery_review_impact",
                                           "20_delivery_monthly"]),
        ("5. Satisfaction drivers (BQ4)", ["21_satisfaction_scores",
                                           "22_satisfaction_test_late_vs_score",
                                           "23_satisfaction_test_lateness_detractor",
                                           "24_satisfaction_test_freight",
                                           "25_satisfaction_test_category"]),
        ("6. Sellers and categories (BQ5)", ["27_seller_concentration", "28_seller_scorecard",
                                             "29_category_table", "26_seller_pareto"]),
    ]
    for title, tables in sections:
        a(f"## {title}")
        a("")
        for name in tables:
            df = _read(name)
            if df.empty:
                continue
            a(f"### `{name}`")
            a("")
            a(md_table(df, max_rows=25))
            a("")

    a("## Reproducibility")
    a("")
    a("```")
    a("make load && make quality && make analyze && make report")
    a("```")
    a("")
    a("Every table above is regenerated by that command chain. Figures live in `reports/figures/`.")
    a("")

    out = config.REPORTS_DIR / "results_pack.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    LOG.info("wrote %s (%d lines)", out, len(lines))
    return str(out)


if __name__ == "__main__":
    build()
